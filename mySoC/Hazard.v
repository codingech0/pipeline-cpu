// Hazard.v
`timescale 1ns / 1ps
`include "defines.vh"

module Hazard (
    input  wire [ 4:0]  id_rs1,
    input  wire [ 4:0]  id_rs2,
    input  wire [ 4:0]  ex_rd,
    input  wire         ex_is_ld_st,
    input  wire         ex_rf_we,
    output wire         stall,
    output wire         flush
);

    // Stall for load-use hazard
    // If EX stage is a load instruction and its destination is used by ID stage
    assign stall = ex_is_ld_st && ex_rf_we &&
                   ((ex_rd != 5'h0) && (ex_rd == id_rs1 || ex_rd == id_rs2));

    // Flush for branch instructions (handled in IF stage)
    // Also flush on jumps
    assign flush = 1'b0;  // Will be generated by branch control

endmodule
